/**
 * Markdown projections of the JSON truth layer.
 *
 * These files exist so a human can review the project from a checkout — the
 * plan, the feed digest, the asset manifest and the recovery history — without
 * opening the workbench. They are strictly derived: nothing reads them back,
 * and deleting `md/` costs one refresh.
 *
 * Every renderer is a pure function of the documents it is handed, so the
 * store's coalesced refresh cannot produce a torn view mid-mutation.
 */

import { clip } from './util.js'

const STATUS_LABEL = {
  pending: '待开始',
  in_progress: '进行中',
  paused: '已暂停',
  done: '已完成',
  locked_by_interrupt: '因中断锁定',
}

function stamp(iso) {
  if (!iso) return '—'
  const date = new Date(iso)
  if (Number.isNaN(date.getTime())) return String(iso)
  return date.toISOString().replace('T', ' ').slice(0, 19)
}

function actorLabel(actor) {
  if (!actor) return 'system'
  const name = actor.name ?? actor.id ?? 'unknown'
  return actor.type === 'human' ? `${name} (human)` : `${name}`
}

function mdCell(text) {
  return String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')
}

function header(project, title) {
  return [
    `# ${title} — ${project.title}`,
    '',
    `> Generated by ai-buddy from the JSON truth layer. **Do not edit by hand:** the next`,
    `> mutation overwrites this file. Project \`${project.id}\`, updated ${stamp(project.updatedAt)}.`,
    '',
  ]
}

// --------------------------------------------------------------------- feed

export function renderFeedMd(bundle) {
  const events = bundle.feed.events ?? []
  const lines = header(bundle.project, '协作动态')
  const pinned = events.filter((e) => e.pinned)
  if (pinned.length > 0) {
    lines.push('## 需要人工关注（锁定/高亮）', '')
    for (const event of pinned) {
      lines.push(`- **${stamp(event.at)}** ${actorLabel(event.actor)} — ${clip(event.content, 300)}`)
    }
    lines.push('')
  }
  lines.push(`## 事件流（最近 ${Math.min(events.length, 200)} / 共 ${events.length}）`, '')
  const recent = events.slice(Math.max(0, events.length - 200))
  for (const event of recent) {
    const tags = [event.kind, event.category, `source:${event.source}`]
    if (event.taskId) tags.push(`task:${event.taskId}`)
    if (event.planItemId) tags.push(`plan:${event.planItemId}`)
    if (event.assetId) tags.push(`asset:${event.assetId}`)
    lines.push(
      `- \`${event.id}\` **${stamp(event.at)}** ${actorLabel(event.actor)} ` +
        `(${tags.join(' · ')}) — ${clip(event.content, 400)}`,
    )
  }
  if (events.length === 0) lines.push('_暂无动态。_')
  lines.push('')
  return lines.join('\n')
}

// --------------------------------------------------------------------- plan

export function renderPlanMd(bundle) {
  const items = bundle.plan.items ?? []
  const tasks = bundle.tasks.tasks ?? []
  const lines = header(bundle.project, '计划看板')
  const byId = new Map(items.map((i) => [i.id, i]))

  for (const status of ['in_progress', 'pending', 'paused', 'locked_by_interrupt', 'done']) {
    const group = items.filter((i) => i.status === status)
    if (group.length === 0) continue
    lines.push(`## ${STATUS_LABEL[status]}（${group.length}）`, '')
    lines.push('| 条目 | 负责 Agent | 优先级 | 依赖 | 截止 | 绑定对话 | 阻塞 |')
    lines.push('| --- | --- | --- | --- | --- | --- | --- |')
    for (const item of group.sort((a, b) => (b.priority ?? 0) - (a.priority ?? 0))) {
      const deps = (item.dependsOn ?? []).map((id) => byId.get(id)?.title ?? id).join('、') || '—'
      const task = tasks.find((t) => t.planItemId === item.id)
      lines.push(
        `| \`${item.id}\` ${mdCell(item.title)} | ${mdCell(item.assignee ?? '未指派')} | ` +
          `${item.priority ?? 0} | ${mdCell(deps)} | ${item.dueAt ? stamp(item.dueAt) : '—'} | ` +
          `${task ? `\`${task.id}\`` : '—'} | ${(item.blockedBy ?? []).length > 0 ? '上游阻塞' : '—'} |`,
      )
    }
    lines.push('')
  }
  if (items.length === 0) lines.push('_暂无计划条目。_', '')

  const locked = items.filter((i) => i.status === 'locked_by_interrupt')
  if (locked.length > 0) {
    lines.push('## ⚠ 因意外中断锁锁定', '')
    for (const item of locked) {
      lines.push(`- \`${item.id}\` ${item.title} — ${item.lastNote || '自动恢复连续失败，等待人工裁决。'}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}

// ------------------------------------------------------------------- assets

export function renderAssetsMd(bundle) {
  const assets = (bundle.assets.assets ?? []).filter((a) => a.deletedAt === null || a.deletedAt === undefined)
  const lines = header(bundle.project, '资产清单')
  lines.push(`共 ${assets.length} 项。`, '')
  lines.push('| 资产 | 目录 | 版本 | 大小 | 所有者 | 可见范围 | 高风险 | 来源对话 |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const asset of assets) {
    const scope =
      (asset.allowedAgents ?? []).length === 0 ? '全项目' : asset.allowedAgents.join('、')
    lines.push(
      `| \`${asset.id}\` ${mdCell(asset.name)} | ${mdCell(asset.folder || '/')} | v${asset.version ?? 1} | ` +
        `${Math.max(1, Math.round((asset.bytes ?? 0) / 1024))} KB | ${mdCell(asset.ownerId)} | ` +
        `${mdCell(scope)} | ${asset.highRisk ? '是' : '—'} | ` +
        `${asset.sourceTaskId ? `\`${asset.sourceTaskId}\`${asset.sourceLocked ? '（已锁定）' : ''}` : '—'} |`,
    )
  }
  lines.push('')
  return lines.join('\n')
}

// ------------------------------------------------------------------- resume

export function renderResumeMd(bundle, resumeStates = []) {
  const tasks = bundle.tasks.tasks ?? []
  const lines = header(bundle.project, '恢复历史')
  if (resumeStates.length === 0 && tasks.length === 0) {
    lines.push('_暂无恢复记录。_', '')
    return lines.join('\n')
  }
  for (const state of resumeStates) {
    const task = tasks.find((t) => t.conversationId === state.conversationId)
    const lock = state.interruptLock ?? {}
    lines.push(`## 对话 \`${state.conversationId}\`${task ? ` — ${task.title}` : ''}`, '')
    lines.push(`- 恢复锁：\`${state.resumeLock?.state ?? 'idle'}\`` +
      `${state.resumeLock?.holder ? `（持有者 ${state.resumeLock.holder}）` : ''}`)
    lines.push(`- 意外中断锁：\`${lock.state ?? 'unlocked'}\`，连续失败 ${lock.consecutiveFailures ?? 0} 次`)
    if (lock.lastFailureReason) lines.push(`- 最近失败原因：${clip(lock.lastFailureReason, 400)}`)
    if (lock.lockedAt) lines.push(`- 锁定时间：${stamp(lock.lockedAt)}（由 ${lock.lockedBy ?? 'system'}）`)
    lines.push(`- 最近恢复：${stamp(state.lastResumeAt)}；最近成功：${stamp(state.lastSucceededAt)}`)
    const history = Array.isArray(task?.resumeHistory) ? task.resumeHistory : []
    if (history.length > 0) {
      lines.push('', '| 时间 | 触发 | 结果 | 错误摘要 |', '| --- | --- | --- | --- |')
      for (const attempt of history.slice(-20)) {
        lines.push(
          `| ${stamp(attempt.at)} | ${mdCell(attempt.trigger ?? 'auto')} | ` +
            `${mdCell(attempt.outcome ?? 'unknown')} | ${mdCell(clip(attempt.failure ?? '', 120) || '—')} |`,
        )
      }
    }
    lines.push('')
  }
  return lines.join('\n')
}
